import { DocumentPage, DocumentChunk, DocumentRecord } from '../types';

export interface ChunkOptions {
  targetTokens?: number; // default ~700 tokens (~2800 chars)
  minTokens?: number;    // default ~400 tokens (~1600 chars)
  overlapTokens?: number;// default ~100 tokens (~400 chars, ~15%)
}

/**
 * Approximate token count helper: ~4 characters per token in English
 */
export function estimateTokens(text: string): number {
  return Math.ceil(text.trim().length / 4);
}

/**
 * Detect headings in academic and technical texts
 */
function extractHeading(text: string): string | undefined {
  const headingMatch = text.match(/^(?:#+\s*|[0-9]+\.[0-9]*\s+|Chapter\s+[0-9]+|Section\s+[0-9]+:?\s*)([^\n]+)/im);
  if (headingMatch && headingMatch[1]) {
    return headingMatch[1].trim();
  }
  return undefined;
}

/**
 * Section 15 & 16: Page-Aware Semantic Chunker
 * Breaks document pages into semantic chunks while retaining:
 * - 1-based page coordinates (pageStart, pageEnd)
 * - Structural continuity (paragraphs, headings)
 * - 15% sliding window overlap
 */
export function chunkDocumentPages(
  documentId: string,
  knowledgeBaseId: string,
  userId: string,
  filename: string,
  pages: DocumentPage[],
  options: ChunkOptions = {}
): DocumentChunk[] {
  const targetChars = (options.targetTokens || 700) * 4; // ~2800 chars
  const overlapChars = (options.overlapTokens || 105) * 4; // ~420 chars (15%)

  const chunks: DocumentChunk[] = [];
  let chunkIndex = 0;

  // Linear accumulation with page tracking
  interface TextSlice {
    text: string;
    page: number;
    isHeading?: boolean;
  }

  const slices: TextSlice[] = [];

  for (const page of pages) {
    if (!page.text || page.text.trim().length === 0) continue;

    // Split page into paragraphs or sections
    const paragraphs = page.text.split(/\n\s*\n/);
    for (const paragraph of paragraphs) {
      const cleanPara = paragraph.trim();
      if (!cleanPara) continue;

      const isHeading = !!extractHeading(cleanPara);
      slices.push({
        text: cleanPara,
        page: page.pageNumber,
        isHeading,
      });
    }
  }

  // If no slices could be formed (e.g. empty or scanned document)
  if (slices.length === 0) {
    return [];
  }

  let currentSliceGroup: TextSlice[] = [];
  let currentGroupChars = 0;

  const flushGroup = () => {
    if (currentSliceGroup.length === 0) return;

    const combinedText = currentSliceGroup.map(s => s.text).join('\n\n');
    const pageStart = Math.min(...currentSliceGroup.map(s => s.page));
    const pageEnd = Math.max(...currentSliceGroup.map(s => s.page));
    const detectedHeading = currentSliceGroup.map(s => extractHeading(s.text)).find(Boolean);

    chunks.push({
      id: `chk_${documentId}_${chunkIndex}`,
      documentId,
      knowledgeBaseId,
      userId,
      chunkIndex,
      content: combinedText,
      pageStart,
      pageEnd,
      embedding: [], // Generated by EmbeddingProvider
      metadata: {
        heading: detectedHeading,
        tokenCount: estimateTokens(combinedText),
        filename,
      },
    });

    chunkIndex++;

    // Calculate overlap: retain trailing slices that fit in overlapChars
    let retainedSlices: TextSlice[] = [];
    let retainedChars = 0;
    for (let i = currentSliceGroup.length - 1; i >= 0; i--) {
      const slice = currentSliceGroup[i];
      if (retainedChars + slice.text.length <= overlapChars) {
        retainedSlices.unshift(slice);
        retainedChars += slice.text.length;
      } else {
        break;
      }
    }

    currentSliceGroup = retainedSlices;
    currentGroupChars = retainedChars;
  };

  for (let i = 0; i < slices.length; i++) {
    const slice = slices[i];
    const sliceChars = slice.text.length;

    // If slice alone is larger than target, chunk it into sentence blocks
    if (sliceChars > targetChars) {
      const sentences = slice.text.match(/[^.!?]+[.!?]+(\s|$)|[^.!?]+$/g) || [slice.text];
      for (const sent of sentences) {
        const cleanSent = sent.trim();
        if (!cleanSent) continue;

        if (currentGroupChars + cleanSent.length > targetChars && currentSliceGroup.length > 0) {
          flushGroup();
        }

        currentSliceGroup.push({ text: cleanSent, page: slice.page });
        currentGroupChars += cleanSent.length;
      }
      continue;
    }

    // If adding slice exceeds target, flush
    if (currentGroupChars + sliceChars > targetChars && currentSliceGroup.length > 0) {
      flushGroup();
    }

    currentSliceGroup.push(slice);
    currentGroupChars += sliceChars;
  }

  // Flush remaining
  if (currentSliceGroup.length > 0) {
    flushGroup();
  }

  return chunks;
}

/**
 * Text extractor for raw uploaded PDF / Document data
 * Handles raw PDF text extraction, plain text, and simulated page detection
 */
export function extractPagesFromRawContent(
  filename: string,
  rawContent: string
): { pages: DocumentPage[]; isScanned: boolean } {
  // If content is a structured PDF dump or contains explicit page breaks
  if (rawContent.includes('--- PAGE ') || rawContent.includes('=== Page ')) {
    const parts = rawContent.split(/(?:--- PAGE |=== Page )(\d+)(?: ---| ===)/g);
    const pages: DocumentPage[] = [];
    for (let i = 1; i < parts.length; i += 2) {
      const pageNum = parseInt(parts[i], 10);
      const text = (parts[i + 1] || '').trim();
      if (text) {
        pages.push({ pageNumber: pageNum, text });
      }
    }
    if (pages.length > 0) {
      return { pages, isScanned: false };
    }
  }

  // Check for scanned / non-textual indicators
  const alphaChars = rawContent.replace(/[^a-zA-Z0-9]/g, '').length;
  if (rawContent.length > 200 && alphaChars / rawContent.length < 0.15) {
    return {
      pages: [],
      isScanned: true,
    };
  }

  // Default: estimate ~2,500 characters per typical PDF page
  const PAGE_CHAR_SIZE = 2400;
  const pages: DocumentPage[] = [];
  const textLength = rawContent.length;

  if (textLength === 0) {
    return { pages: [], isScanned: true };
  }

  let offset = 0;
  let pageIndex = 1;

  while (offset < textLength) {
    let nextOffset = Math.min(offset + PAGE_CHAR_SIZE, textLength);
    // Try to cut at nearest paragraph or newline
    if (nextOffset < textLength) {
      const naturalCut = rawContent.lastIndexOf('\n\n', nextOffset);
      if (naturalCut > offset + 1000) {
        nextOffset = naturalCut + 2;
      }
    }

    const pageText = rawContent.slice(offset, nextOffset).trim();
    if (pageText) {
      pages.push({
        pageNumber: pageIndex,
        text: pageText,
      });
      pageIndex++;
    }

    offset = nextOffset;
  }

  return { pages, isScanned: false };
}
